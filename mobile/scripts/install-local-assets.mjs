/**
 * Local-only asset installer.
 *
 * Copies the typefaces out of the decoded artifact into mobile/assets/fonts/
 * (git-ignored) and rewrites src/theme/fonts.local.ts with static requires so
 * Metro bundles them. Nothing is published: the binaries stay on this machine.
 *
 *   node scripts/install-local-assets.mjs [--decoded <dir>] [--revert]
 *
 * Default decoded dir: ../analysis/apktool
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const mobileRoot = path.resolve(here, '..');
const args = process.argv.slice(2);
const revert = args.includes('--revert');
const decodedArg = args.indexOf('--decoded');
const decodedRoot = path.resolve(
  mobileRoot,
  decodedArg >= 0 ? args[decodedArg + 1] : '../analysis/apktool',
);

const FONT_SRC = path.join(
  decodedRoot,
  'assets/composeResources/claude.theme.generated.resources/font',
);
const FONT_DEST = path.join(mobileRoot, 'assets', 'fonts');
const LOCAL_TS = path.join(mobileRoot, 'src', 'theme', 'fonts.local.ts');

// wire name -> { family, file }
const MAP = {
  sans: { family: 'AnthropicSans', file: 'anthropic_sans.ttf' },
  serif: { family: 'AnthropicSerif', file: 'anthropic_serif.ttf' },
  mono: { family: 'JetBrainsMono', file: 'jetbrains_mono.ttf' },
};

const stub = `export const LOCAL_FONT_ASSETS: Record<string, any> = {};

export const LOCAL_FONT_FAMILIES: { sans?: string; serif?: string; mono?: string } = {};
`;

if (revert) {
  fs.writeFileSync(LOCAL_TS, stub);
  console.log('reverted fonts.local.ts to the empty stub');
  process.exit(0);
}

if (!fs.existsSync(FONT_SRC)) {
  console.error(`Font dir not found: ${FONT_SRC}\nDecode the artifact first (see analysis/00-target.md).`);
  process.exit(1);
}

fs.mkdirSync(FONT_DEST, { recursive: true });

const assets = [];
const families = [];
for (const [kind, { family, file }] of Object.entries(MAP)) {
  const src = path.join(FONT_SRC, file);
  if (!fs.existsSync(src)) {
    console.warn(`skip (missing): ${file}`);
    continue;
  }
  fs.copyFileSync(src, path.join(FONT_DEST, file));
  assets.push(`  ${family}: require('../../assets/fonts/${file}'),`);
  families.push(`${kind}: ${JSON.stringify(family)}`);
  console.log(`copied ${file}`);
}

const ts = `// Generated by scripts/install-local-assets.mjs — LOCAL ONLY, git-ignored fonts.
export const LOCAL_FONT_ASSETS: Record<string, any> = {
${assets.join('\n')}
};

export const LOCAL_FONT_FAMILIES: { sans?: string; serif?: string; mono?: string } = {
  ${families.join(',\n  ')}
};
`;
fs.writeFileSync(LOCAL_TS, ts);

console.log(`\nwrote ${path.relative(mobileRoot, LOCAL_TS)}`);
console.log('These files stay on this machine (mobile/assets/fonts/ is git-ignored).');
console.log('Restart the dev server to pick them up.');
